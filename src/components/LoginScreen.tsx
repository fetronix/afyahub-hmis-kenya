const BrandLogo: React.FC<BrandLogoProps> = ({
  variant,
  className = 'h-12 w-auto',
  fallbackClassName = '',
  priority = false,
}) => {
  const [failed, setFailed] = useState(false);
  const isPlaque = variant === 'plaque';

  if (failed) {
    return (
      <div
        className={`inline-flex items-center gap-3 rounded-lg px-4 py-2.5 ${
          isPlaque ? 'bg-[#142143]' : ''
        } ${fallbackClassName}`}
      >
        <span
          aria-hidden="true"
          className="flex h-9 w-9 shrink-0 items-center justify-center rounded-md bg-[#1888B5] text-lg font-bold text-white"
        >
          +
        </span>
        <span className="min-w-0 leading-tight">
          <span className="block text-lg font-extrabold tracking-[0.08em] text-[#1888B5]">
            SYRONA
          </span>
          <span className="block text-[10px] font-semibold tracking-[0.18em] text-white">
            MEDICAL CENTER
          </span>
        </span>
      </div>
    );
  }

  return (
    <img
      src={isPlaque ? LOGO_PLAQUE_SRC : LOGO_SRC}
      alt="Syrona Medical Center"
      draggable={false}
      decoding={priority ? 'sync' : 'async'}
      onError={() => setFailed(true)}
      className={`select-none object-contain ${className}`}
    />
  );
};

